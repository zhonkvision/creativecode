/**
 * Universal Multiline ASCII Art Renderer
 * @param {string} text - Raw input text (multiline supported with \n)
 * @param {string} fontKey - Identifier for TheDraw/FIGlet font
 * @param {number} spacing - Horizontal character kerning (-1 to +6)
 * @param {string} align - 'left', 'center', or 'right'
 * @param {string} frameType - 'none', 'terminal', 'double', 'brackets', 'stars', 'slash', 'block'
 */
export function renderTheDrawArt(text, fontKey = 'acid-blue', spacing = 1, align = 'center', frameType = 'none') {
  const font = THEDRAW_FONTS[fontKey] || THEDRAW_FONTS['acid-blue'];
  const rawInput = (text || 'CREATIVE CODE');
  const inputLines = rawInput.split('\n');
  const fontHeight = font.height;
  const renderedBlockLines = [];

  const spaceStr = ' '.repeat(Math.max(0, spacing));

  // Process each line of text
  for (const singleLine of inputLines) {
    const clean = singleLine.toUpperCase();
    const lineRows = Array(fontHeight).fill('');

    for (let i = 0; i < clean.length; i++) {
      const char = clean[i];
      const glyph = font.map[char] || font.map[' '] || createGlyphFallback(char, fontHeight);
      for (let r = 0; r < fontHeight; r++) {
        const glyphRow = glyph[r] || '   ';
        lineRows[r] += glyphRow + (i < clean.length - 1 ? spaceStr : '');
      }
    }
    renderedBlockLines.push(...lineRows);
  }

  // Calculate maximum line length across all rows
  const maxLen = Math.max(...renderedBlockLines.map(l => l.length), 1);

  // Apply Alignment (Left, Center, Right)
  const alignedLines = renderedBlockLines.map(line => {
    const diff = Math.max(0, maxLen - line.length);
    if (align === 'center') {
      const leftPad = Math.floor(diff / 2);
      const rightPad = diff - leftPad;
      return ' '.repeat(leftPad) + line + ' '.repeat(rightPad);
    } else if (align === 'right') {
      return ' '.repeat(diff) + line;
    }
    return line + ' '.repeat(diff);
  });

  let finalLines = [...alignedLines];

  // Apply Border Framing
  if (frameType && frameType !== 'none') {
    const contentLen = maxLen;
    if (frameType === 'terminal') {
      const top = '┌' + '─'.repeat(contentLen + 4) + '┐';
      const bot = '└' + '─'.repeat(contentLen + 4) + '┘';
      finalLines = [
        top,
        '│  ' + ' '.repeat(contentLen) + '  │',
        ...alignedLines.map(l => `│  ${l}  │`),
        '│  ' + ' '.repeat(contentLen) + '  │',
        bot
      ];
    } else if (frameType === 'double') {
      const top = '╔' + '═'.repeat(contentLen + 4) + '╗';
      const bot = '╚' + '═'.repeat(contentLen + 4) + '╝';
      finalLines = [
        top,
        '║  ' + ' '.repeat(contentLen) + '  ║',
        ...alignedLines.map(l => `║  ${l}  ║`),
        '║  ' + ' '.repeat(contentLen) + '  ║',
        bot
      ];
    } else if (frameType === 'brackets') {
      finalLines = alignedLines.map(l => `[ / ${l} / ]`);
    } else if (frameType === 'stars') {
      const top = '*'.repeat(contentLen + 6);
      finalLines = [
        top,
        ...alignedLines.map(l => `** ${l} **`),
        top
      ];
    } else if (frameType === 'slash') {
      const top = '//' + '='.repeat(contentLen + 2) + '\\\\';
      const bot = '\\\\' + '='.repeat(contentLen + 2) + '//';
      finalLines = [
        top,
        ...alignedLines.map(l => `|| ${l} ||`),
        bot
      ];
    } else if (frameType === 'block') {
      const top = '█'.repeat(contentLen + 6);
      finalLines = [
        top,
        ...alignedLines.map(l => `██ ${l} ██`),
        top
      ];
    }
  }

  return finalLines.join('\n');
}
